  t.S.shop.payroll = 180;
  t.S.veh.jeep.trip = null;
  t.setDraft({ egg: 5 });
  assert(t.dispatch('jeep'));
  const cancelled = t.S.veh.jeep.trip;
  t.refund(cancelled); t.refund(cancelled);
  assert.equal(t.S.inv.egg, 16, 'refund must be exact and idempotent');
  t.S.veh.jeep.trip = null;
  t.allowTrip(false);
