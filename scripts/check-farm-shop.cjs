  assert.equal(t.S.inv.egg, 16);
  assert.deepEqual(t.incoming(), { bigas: 5, egg: 4 });
  assert.equal(t.S.shop.stock.egg, undefined, 'stock must not appear before delivery');
  assert(t.deliver(delivery));
  assert.equal(t.deliver(delivery), false, 'duplicate unload');
  assert.equal(t.S.shop.stock.bigas, 5);
  t.refund(delivery);
  assert.equal(t.S.inv.egg, 16, 'delivered goods must not also be refunded');
  const money = t.S.coins;
